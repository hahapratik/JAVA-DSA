public class PrePost {
    public static void main(String[] args) {
        // post/pre Increnment
        int a = 10;
        int b = ++a;
        // a++ => a= a+1;
        System.out.println("a: " + a);
        System.out.println("b: " + b);
        // post/pre decrenment
        int c = 10;
        int d = c--;
        // a++ => a= a+1;
        System.out.println("c: " + c);//system out
        System.out.println("d: " + d);//print

    }
}
