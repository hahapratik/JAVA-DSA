public class While {
  public static void main(String[] args) {
      // Initialize a counter variable 'n' to 0. This variable will control the loop.
    int n = 0;
 while (n<10) { // Start a 'while' loop that continues as long as 'n' is less than 10.
      System.out.println("HELL0"); // Print "HELL0" to the console. This is the action performed in each iteration of the loop.
      n++; // Increment 'n' by 1 in each iteration.  This ensures that the loop eventually terminates.
 } // The loop will execute 10 times, printing "HELL0" each time.
  }  
}


