public class Q8 {
   public static void main(String[] args) {
      // Initialize two integer variables a and b with values 63 and 36 respectively.
      int a = 63, b = 36;
      // Use the ternary operator to assign a boolean value to x based on whether a is less than b.
      boolean x = (a < b) ? true : false;
      // Use the ternary operator to assign the larger of a and b to the integer variable y.
      int y = (a > b) ? a : b;
      // Print the boolean value of x to the console.
      System.out.println(x);
      // Print the integer value of y to the console.
      System.out.println(y);
   }
}
