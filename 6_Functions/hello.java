// Define a public class named 'hello'
public class hello {
    
    // Define a static method named 'hie' that prints "HELLO WORLD" to the console
    public static void hie () {
        System.out.println("HELLO WORLD");
    }
    
    // The main method is the entry point of the program
    public static void main(String[] args) {
        // Call the 'hie' method to print the message to the console
        hie();
    }
}